import random

# ردود حسب الكلمات المفتاحية في التعليق
KEYWORD_RESPONSES = {
    "سلام": [
        "وعليكم السلام يا غالي، مرحب بيك وبأهل الكلان الكل!",
        "أهلا وسهلا، نورت اللايف يا ملك."
    ],
    "كيفك": [
        "والله الحمد لله يا خويا، نقاوموا في الدنيا والجو ماشي.",
        "صافية لبن, والحمد لله. وأنت شنو أحوالك؟"
    ],
    "شكون": [
        "أنا صاحب الجو، قاعد معاكم نصنعوا شوية ضحكة ونبّروا على هموم الدنيا!",
        "أنا ولد الدار، جيت باش نعمل جو مع أحلى ناس."
    ],
    "تونس": [
        "يا خويا تونس الخضراء، تحية لأهل صفاقس وكل بلاصة تسمع فينا!",
        "بلادنا عزيزة والجو فيها ديما حار."
    ]
}

RANDOM_COMMENTS = [
    "صحيح والله، دبرت عليها يا معلم!",
    "علاش هكا عاد؟ تي هذي حكاية فارغة.",
    "اسمعني، اللي ما يفهمكش حطو تحت الساقين وراسك عالي.",
    "يا راجل هدي روحك، الدنيا فانية والجو ماشي قدام."
]

WELCOME_RESPONSES = [
    "أهلاً بيك يا غالي، نورت اللايف! اعطيني البارتاج وراك لَباد.",
    "مرحباً بالناس الكل، اقعدوا على رويحتكم، الليلة دايخة!"
]

GIFT_RESPONSES = [
    "يا سلام! كرتوشة عياط للغالي اللي بعث الهدية، يعطيكم الصحة!",
    "ربي يفضلك يا معلم، وصلت الهدية وزينت اللايف!"
]

def get_comment_reply(comment_text):
    text_lower = comment_text.lower()
    # البحث عن كلمات مفتاحية
    for keyword, replies in KEYWORD_RESPONSES.items():
        if keyword in text_lower:
            return random.choice(replies)
    # إذا لم توجد كلمة مفتاحية، رد عشوائي
    return random.choice(RANDOM_COMMENTS)

def get_welcome_reply():
    return random.choice(WELCOME_RESPONSES)

def get_gift_reply(gift_name, username):
    return f"يعطيك الصحة يا {username} على الهدية المزينة {gift_name}, كبرت بينا!"
